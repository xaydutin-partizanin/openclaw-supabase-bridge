-- Supabase <-> OpenClaw durable mailbox and run ledger.
-- Apply as the project owner. RLS is enabled and no anon/authenticated policy is granted.

create extension if not exists pgcrypto;

create table if not exists public.providers (
  id uuid primary key default gen_random_uuid(),
  provider_key text not null unique,
  name text not null,
  available boolean not null default false,
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.agent_configs (
  id uuid primary key default gen_random_uuid(),
  config_key text not null unique,
  provider_id uuid not null references public.providers(id) on update cascade on delete restrict,
  runtime text not null,
  agent text not null,
  model text,
  effort text,
  available boolean not null default false,
  is_default boolean not null default false,
  other jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  prompt text not null check (length(btrim(prompt)) > 0),
  requested_config text,
  status text not null default 'pending' check (
    status in ('pending', 'claimed', 'running', 'completed', 'failed', 'cancelled', 'timed_out')
  ),
  claimed_by text,
  claimed_at timestamptz,
  lease_expires_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.runs (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks(id) on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz,
  status text not null default 'created' check (
    status in ('created', 'claimed', 'running', 'completed', 'failed', 'cancelled', 'timed_out')
  ),
  requested_config text,
  used_config text not null,
  fallback_used boolean not null default false,
  fallback_reason text,
  config_id uuid references public.agent_configs(id) on update cascade on delete set null,
  provider_id uuid references public.providers(id) on update cascade on delete set null,
  provider_key text,
  runtime text,
  agent text,
  model text,
  effort text,
  openclaw_task_id text,
  openclaw_run_id text,
  parent_session_key text,
  parent_session_id text,
  error text,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks(id) on update cascade on delete cascade,
  run_id uuid not null unique references public.runs(id) on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  status text not null check (status in ('completed', 'failed', 'cancelled', 'timed_out')),
  report_text text not null,
  report jsonb not null default '{}'::jsonb
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  task_id uuid not null references public.tasks(id) on update cascade on delete cascade,
  run_id uuid not null references public.runs(id) on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  event_ts timestamptz not null,
  source_run_id text,
  source_session_key text,
  source_session_id text,
  source_agent_id text,
  lifecycle_generation text,
  seq bigint,
  stream text,
  event_type text,
  data jsonb not null default '{}'::jsonb
);

create table if not exists public.quota_status (
  id uuid primary key default gen_random_uuid(),
  quota_identity text not null unique,
  provider_id uuid not null references public.providers(id) on update cascade on delete cascade,
  config_id uuid references public.agent_configs(id) on update cascade on delete set null,
  account_key text not null default 'default',
  quota_key text not null,
  remaining numeric,
  limit_value numeric,
  unit text,
  reset_at timestamptz,
  checked_at timestamptz not null,
  status text not null check (status in ('ok', 'unknown', 'unsupported', 'error')),
  source text,
  other jsonb not null default '{}'::jsonb
);

create unique index if not exists agent_configs_one_default_idx
  on public.agent_configs ((is_default)) where is_default;
create index if not exists agent_configs_provider_idx on public.agent_configs(provider_id, available);
create index if not exists tasks_status_created_idx on public.tasks(status, created_at);
